"""Export the exact HTTP schema and business vocabulary; --check detects drift."""

import argparse
import json
import sys
from pathlib import Path
from tempfile import TemporaryDirectory

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.main import create_app  # noqa: E402
from app.pilot.config import Settings  # noqa: E402
from app.selection.contracts import (  # noqa: E402
    CandidateStatus,
    Channel,
    Money,
    ScreeningStatus,
    Window,
)


def export() -> dict[Path, str]:
    with TemporaryDirectory() as directory:
        root = Path(directory)
        schema = create_app(
            settings=Settings(
                mode="pilot",
                data_dir=root,
                public_url="http://localhost",
                demo_db_path=None,
                control_db_path=root / "control.sqlite3",
                workspaces_dir=root / "workspaces",
            )
        ).openapi()
    vocab = {
        kind.__name__: [item.value for item in kind]
        for kind in (Channel, CandidateStatus, ScreeningStatus)
    }
    schema["x-business-vocabulary"] = vocab
    schema["x-value-contracts"] = {
        "Money": Money.model_json_schema(),
        "Window": Window.model_json_schema(),
    }
    lines = ["// Generated by scripts/export_contracts.py; do not edit."]
    for name, values in vocab.items():
        lines += [
            f"export const {name}Values = {json.dumps(values)} as const;",
            f"export type {name} = typeof {name}Values[number];",
        ]
    return {
        ROOT / "docs/implementation/openapi.json": json.dumps(
            schema, ensure_ascii=False, indent=2, sort_keys=True
        )
        + "\n",
        ROOT / "web/src/generated/contracts.ts": "\n".join(lines) + "\n",
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in export().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(
                    "Contract drift: regenerate with .venv/bin/python "
                    f"scripts/export_contracts.py ({path.name})"
                )
        else:
            path.write_text(content)
    print("HTTP schema and frontend vocabulary are in sync.")
